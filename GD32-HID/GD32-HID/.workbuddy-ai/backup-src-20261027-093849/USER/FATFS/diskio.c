/* Definitions of physical drive number for each drive */
#define EX_FLASH 	0

#define FLASH_SECTOR_SIZE 	512			  	 			    	
#define FLASH_BLOCK_SIZE   	8 
uint16_t	FLASH_SECTOR_COUNT = (8*1024*1024/FLASH_SECTOR_SIZE);

